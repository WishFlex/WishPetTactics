    local translatedSet = {}
    for _, v in pairs(activeDict) do
        if type(v) == "string" and v ~= "" and not activeDict[v] then
            translatedSet[v] = true
        end
    end

    local transCache = {}
    local transCachePrev = {}
    local transCacheCount = 0
    local lastTranslatedOut = nil

    local function TranslateColorSpan(prefix, body, suffix)
        local hit = activeDict[body]
        if hit then
            return prefix .. hit .. suffix
        end
        return prefix .. body .. suffix
    end

    function ns:T(str)
        if type(str) ~= "string" or str == "" or str == lastTranslatedOut then return str end
        local exact = activeDict[str]
        if exact then
            lastTranslatedOut = exact
            return exact
        end
        if translatedSet[str] then
            return str
        end

        local cached = transCache[str] or (transCachePrev and transCachePrev[str])
        if cached then
            lastTranslatedOut = cached
            return cached
        end

        -- Fast path: skip regex pattern scan for pure ASCII strings
        if not string.find(str, "[\128-\255]") then
            return str
        end

        local out = str
        if string.find(out, "|c", 1, true) then
            out = string.gsub(out, "(|c%x%x%x%x%x%x%x%x)([^|]+)(|r)", TranslateColorSpan)
        end

        for i = 1, #activePatterns do
            local pair = activePatterns[i]
            out = string.gsub(out, pair[1], pair[2])
        end

        if transCacheCount >= 1000 then
            if not transCachePrev then transCachePrev = {} end
            wipe(transCachePrev)
            transCachePrev, transCache = transCache, transCachePrev
            transCacheCount = 0
        end
        transCache[str] = out
        transCacheCount = transCacheCount + 1
        lastTranslatedOut = out
        return out
    end

    function ns:TF(template, ...)
        local out = string.format(self:T(template), ...)
        lastTranslatedOut = out
        return out
    end
end

ns.L = setmetatable({}, {
    __index = function(_, k)
        return ns:T(k)
    end
})

